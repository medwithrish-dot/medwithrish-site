import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const db = new PGlite();
const owner = randomUUID();
const stranger = randomUUID();
const sql = async name => (await readFile(new URL(`../supabase/${name}.sql`, import.meta.url), "utf8")).replace('create extension if not exists "pgcrypto";', "");
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; grant usage on schema auth to authenticated,anon;
    create table auth.users(id uuid primary key,raw_user_meta_data jsonb not null default '{}');
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant execute on function auth.uid() to authenticated,anon;`);
  for (const name of ["medicforest_interview_platform", "medicforest_interview_dashboard", "medicforest_interview_question_progress", "medicforest_interview_applicant_activity", "medicforest_interview_free_trial"]) await db.exec(await sql(name));
  await db.query("insert into auth.users(id) values ($1),($2)", [owner, stranger]);
  const reserve = async (platform, circuit = randomUUID(), daily = 20) => (await db.query("select to_jsonb(public.reserve_interview_attempt($1,$2::jsonb,$3,300)) as attempt", [owner, JSON.stringify({ ...(platform ? { platform } : {}), mode: "station", station_slug: platform === "dentistry" ? "why-dentistry" : "why-medicine", title: "Practice", circuit_id: circuit, station_index: 0, station_count: 1, preparation_seconds: 0, station_seconds: 480, break_seconds: 0, questions: ["Why this profession?"] }), daily])).rows[0].attempt;
  const original = await reserve();
  await db.query("insert into public.interview_preparation_profiles(user_id,experience) values ($1,'starting')", [owner]);
  const before = (await db.query("select to_jsonb(a) as row from public.interview_attempts a where id=$1", [original.id])).rows[0].row;
  const migration = await sql("medicforest_dentistry_platform");
  await db.exec(migration);
  await db.exec(migration);
  const after = (await db.query("select to_jsonb(a) as row from public.interview_attempts a where id=$1", [original.id])).rows[0].row;
  assert.deepEqual(after, { ...before, platform: "medicine" });
  const dental = await reserve("dentistry");
  assert.notEqual(dental.id, original.id);
  assert.equal(dental.platform, "dentistry");
  assert.equal((await reserve()).id, original.id, "old callers still resume medicine");
  assert.equal((await reserve("dentistry")).id, dental.id, "dentistry resumes only dentistry");
  await db.query("update public.interview_attempts set status='completed',score=case platform when 'medicine' then 70 else 90 end,completed_at=now() where user_id=$1", [owner]);
  await assert.rejects(reserve("dentistry", randomUUID(), 2), /Daily interview limit/, "cost limits stay account-wide");
  await assert.rejects(reserve("invalid"), /Invalid interview platform/);
  await db.query("insert into public.interview_dentistry_preparation_profiles(user_id,experience) values ($1,'polishing')", [owner]);
  await db.query("insert into public.interview_preparation_profiles(user_id,experience) values ($1,'practising') on conflict(user_id) do update set experience=excluded.experience", [owner]);
  assert.equal((await db.query("select experience from public.interview_preparation_profiles")).rows[0].experience, "practising", "old medicine plan saves still work");
  assert.equal((await db.query("select experience from public.interview_dentistry_preparation_profiles")).rows[0].experience, "polishing", "medicine saves cannot overwrite a dental plan");
  await db.query("insert into public.interview_question_progress(user_id,question_id,status,completed_at) values ($1,'iq-01-001','completed',now()),($1,'dq-01-001','completed',now())", [owner]);
  const rows = (await db.query("select question_id,platform from public.interview_question_progress order by question_id")).rows;
  assert.deepEqual(rows, [{ question_id: "dq-01-001", platform: "dentistry" }, { question_id: "iq-01-001", platform: "medicine" }]);
  assert.equal((await db.query("select count(*)::int as n from public.interview_daily_questions where platform='dentistry'")).rows[0].n, 1);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [owner]);
  await db.exec("set role authenticated");
  assert.equal((await db.query("select public.interview_dashboard_totals() as value")).rows[0].value.averageScore, 70);
  assert.equal((await db.query("select public.interview_platform_dashboard_totals('dentistry') as value")).rows[0].value.averageScore, 90);
  await assert.rejects(db.query("update public.interview_attempts set platform='medicine' where platform='dentistry'"), /permission denied/);
  await assert.rejects(db.query("update public.interview_dentistry_preparation_profiles set experience='starting'"), /permission denied/);
  await db.exec("reset role");
  await db.query("select set_config('request.jwt.claim.sub',$1,false)", [stranger]);
  await db.exec("set role authenticated");
  assert.equal((await db.query("select * from public.interview_attempts")).rows.length, 0);
  assert.equal((await db.query("select * from public.interview_question_progress")).rows.length, 0);
  assert.equal((await db.query("select * from public.interview_preparation_profiles")).rows.length, 0);
  assert.equal((await db.query("select * from public.interview_dentistry_preparation_profiles")).rows.length, 0);
  console.log("PASS dentistry migration: rerunnable, medicine preserved, isolated resume/progress/totals, account quotas, owner permissions");
} finally { await db.close(); }
